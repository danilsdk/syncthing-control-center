"""One public login route; every other API router shares require_admin."""

import hmac
from typing import Annotated

from fastapi import APIRouter, Depends, Request, Response, Security
from fastapi.routing import APIRoute
from fastapi.security import APIKeyCookie
from starlette.types import ASGIApp, Message, Receive, Scope, Send

from app.contracts.dto import Error, Login, Session, User
from app.contracts.errors import AppError
from app.registry.authentication import AdministratorAuth
from app.registry.security import COOKIE_NAME, SESSION_SECONDS

cookie_scheme = APIKeyCookie(name=COOKIE_NAME, scheme_name="adminSession", auto_error=False)
ORIGIN_PARAMETER = {
    "name": "Origin",
    "in": "header",
    "required": True,
    "schema": {"type": "string", "format": "uri"},
}
CSRF_PARAMETER = {
    "name": "X-CSRF-Token",
    "in": "header",
    "required": True,
    "schema": {"type": "string", "minLength": 32},
}


def get_auth(request: Request) -> AdministratorAuth:
    return request.app.state.auth


def require_origin(request: Request) -> None:
    origins = request.headers.getlist("Origin")
    if len(origins) != 1 or origins[0] not in request.app.state.settings.allowed_origins:
        raise AppError(403, "origin_forbidden", "Request origin is not allowed")


def require_admin(request: Request, token: Annotated[str | None, Security(cookie_scheme)]) -> User:
    session = get_auth(request).authenticate(token)
    if request.method in {"POST", "PUT", "PATCH", "DELETE"}:
        require_origin(request)
        tokens = request.headers.getlist("X-CSRF-Token")
        supplied = tokens[0] if len(tokens) == 1 else ""
        if not supplied.isascii() or not hmac.compare_digest(supplied, session.csrf_token):
            raise AppError(403, "csrf_invalid", "CSRF token is invalid")
    request.state.admin_session = session
    return session.user


class LoginRoute(APIRoute):
    def get_route_handler(self):
        handler = super().get_route_handler()

        async def origin_first(request: Request) -> Response:
            require_origin(request)
            return await handler(request)

        return origin_first


def _secure_cookie(request: Request) -> bool:
    settings = request.app.state.settings
    return (
        settings.environment == "production"
        or request.url.scheme == "https"
        or all(origin.startswith("https://") for origin in settings.allowed_origins)
    )


public_router = APIRouter(prefix="/api/auth", route_class=LoginRoute)
protected_router = APIRouter(prefix="/auth")


@public_router.post(
    "/login",
    response_model=Session,
    operation_id="login",
    responses={code: {"model": Error} for code in (401, 403, 422, 429, 503)},
    openapi_extra={"parameters": [ORIGIN_PARAMETER], "security": []},
)
def login(
    payload: Login,
    request: Request,
    response: Response,
    auth: Annotated[AdministratorAuth, Depends(get_auth)],
) -> Session:
    token, session = auth.login(
        payload.login,
        payload.password.get_secret_value(),
        request.client.host if request.client else "unknown",
    )
    response.set_cookie(
        COOKIE_NAME,
        token,
        max_age=SESSION_SECONDS,
        expires=session.expires_at,
        httponly=True,
        secure=_secure_cookie(request),
        samesite="lax",
        path="/",
    )
    return session


@protected_router.get(
    "/me",
    response_model=Session,
    operation_id="current_session",
    responses={code: {"model": Error} for code in (401, 422, 503)},
)
def current_session(request: Request) -> Session:
    return request.state.admin_session


@protected_router.post(
    "/logout",
    status_code=204,
    operation_id="logout",
    responses={code: {"model": Error} for code in (401, 403, 422, 503)},
    openapi_extra={"parameters": [ORIGIN_PARAMETER, CSRF_PARAMETER]},
)
def logout(request: Request) -> Response:
    response = Response(status_code=204)
    response.delete_cookie(
        COOKIE_NAME, path="/", httponly=True, secure=_secure_cookie(request), samesite="lax"
    )
    return response


class PrivateApiHeadersMiddleware:
    """Includes auth errors and responses generated by RequestContextMiddleware."""

    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http" or not scope.get("path", "").startswith("/api/"):
            await self.app(scope, receive, send)
            return

        async def private_headers(message: Message) -> None:
            if message["type"] == "http.response.start":
                headers = [
                    (k, v)
                    for k, v in message.get("headers", [])
                    if k.lower()
                    not in {
                        b"cache-control",
                        b"pragma",
                    }
                ]
                message = {
                    **message,
                    "headers": [
                        *headers,
                        (b"cache-control", b"no-store"),
                        (b"pragma", b"no-cache"),
                    ],
                }
            await send(message)

        await self.app(scope, receive, private_headers)
